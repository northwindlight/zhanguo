"""Rescore this runner's own captured states with and without the soft prior."""
import argparse
import gzip
import json
from pathlib import Path
import pickle

import torch

from rl.economy.model import collate, load_policy, prepare


def main():
    p = argparse.ArgumentParser(description=__doc__)
    p.add_argument('--rows', type=Path, required=True)
    p.add_argument('--checkpoint', type=Path, required=True)
    p.add_argument('--out', type=Path, required=True)
    p.add_argument('--from-period', type=int, default=70)
    p.add_argument('--weight', type=float, default=.5)
    args = p.parse_args()
    torch.set_num_threads(1)
    model, _ = load_policy(args.checkpoint)
    # Captures must be generated by econ_causal_probe, not arbitrary downloads.
    with gzip.open(args.rows, 'rb') as source:
        captured = pickle.load(source)
    records = []
    model.config['exec_prior_weight'] = args.weight
    with torch.inference_mode():
        for entry in captured:
            if entry['attempt'] or entry['period'] < args.from_period:
                continue
            row = entry['row']
            logits, _, execution = model(prepare(collate([row]), 'cpu'), return_value=True)
            logits, execution = logits[0], execution[0]
            plain = logits-args.weight*(execution.sigmoid()+1e-3).log()
            before, after = int(logits.argmax()), int(plain.argmax())
            power = [i for i, (kind, values) in enumerate(entry['actions']) if kind == 'build'
                     and values.get('kind') in ('native:wood-power-plant', 'native:oil-power-plant')
                     and row['legal'][i]]
            best = max(power, key=lambda i: float(plain[i])) if power else None
            records.append(dict(period=entry['period'], energy=entry.get('energy'),
                prior_action=entry['actions'][before], plain_action=entry['actions'][after],
                changed=before != after, executable_power=len(power),
                power_low_exec=sum(float(execution[i].sigmoid()) < .5 for i in power),
                best_power=None if best is None else dict(action=entry['actions'][best],
                    executable_probability=float(execution[best].sigmoid()),
                    plain_logit=float(plain[best]), prior_logit=float(logits[best]),
                    prior_contribution=float(logits[best]-plain[best])),
                selected_plain_logit=float(plain[before]), selected_prior_logit=float(logits[before])))
    args.out.parent.mkdir(parents=True, exist_ok=True)
    args.out.write_text(json.dumps(dict(weight=args.weight, records=records), ensure_ascii=False, indent=2)+'\n')
    print(json.dumps(dict(states=len(records), changed=sum(r['changed'] for r in records),
                          power_low_exec_states=sum(r['power_low_exec'] > 0 for r in records))))


if __name__ == '__main__':
    main()
