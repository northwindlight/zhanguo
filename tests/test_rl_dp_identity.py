def dump(o):
    """`assess` 的全部可观测输出，浮点用 `repr`（往返精确 ⇒ 逐位可比）。"""
    return dict(
        p_win={k: repr(v) for k, v in sorted(o.p_win.items())},
        p_lose={k: repr(v) for k, v in sorted(o.p_lose.items())},
        p_draw=repr(o.p_draw),
        p_hold={k: repr(v) for k, v in sorted(o.p_hold.items())},
        e_rounds=repr(o.e_rounds),
        e_loss={k: repr(v) for k, v in sorted(o.e_loss.items())},
        p_rounds=[repr(x) for x in o.p_rounds],
        round_bins=[repr(x) for x in o.round_bins()],
        truncated=repr(o.truncated),
    )


