# ★★★ 2026-09-26：**从"零初始化"改成"小而非零"** —— 我实测抓到零初始化的代价：
#   零初始化让 `upd ≡ 0` 逐位成立（对照干净），**但它同时把读路径的梯度掐死了**：
#   初值槽不含**状态** ⇒ 读路径能学到的最多是"用 `mem0` 这个常数"（实测：置零槽
