# 5'. 军队 token 的**尾部追加段**（在规则表那 4 列**之后**；宽度冻结）
# ===========================================================================
# ★★ **这一段的语义 = "这支军正身处的那场仗，从它自己那一方看是什么样"**。
#   每条军队 token 都带**它自己势力**的概率（`Odds.p_win[它那一方]`）——
#   两国共用同一套编码 ⇒ 甲看到的"甲的概率"就是乙看到的"乙的概率"，自对弈不失衡。
#
#   ★★ **为什么战斗概率要挂在军队 token 上（而不是只放网格）**：
#     网格 = **视野外接框**（本线口径），而**交战格绝大多数在框外** ——
#     实测（8 局随机对局，每 3 步采样）：8×8 交战格可见率 **27%~66%**、
#     **16×16 只有 0%~7%**（有一局 1202 个样本**一个都不在视野里**）。
#     军队 token 则**与视野无关**（我军恒在 token 里）⇒ 放在这里
#     **大地图上也是活的**。网格那份也留着（同一条信息，两种读法：
#     网格给"候选要去的那个格子"直接 gather，token 给"哪支军最危险"）。
#
#   ★ **撤退保命概率**（用户 2026-09-24：「**撤退保住军队的概率**是多少」）
#     是**逐军不同**的量（同格两支军血不同 ⇒ 撤了活下来的概率不同）⇒
#     它**只能**在军队 token 上（网格"一格一个数"只能取 max/min，那是把精确量压成近似量）。
#     ⚠ **沙盒目前没有 `retreat` 动作**（`KIND` 只有 hold/move/attack）⇒ 这一列现在是
#     **纯情报**：它精确回答"这支军在这仗里接下来会怎样"（撤得掉 / 撤不掉）
#     —— 正是"要不要再往里填兵"的判据（撤不掉 ⇒ 送进去也是陪葬）。
#     `retreat` 一旦进 `KIND`，这一列**立刻**变成可行动作的精确预期，不用再改观测。
#
#   ★ 没在交战（或看不见那场仗）⇒ 整段全 0，**只有撤退那一列是 1.0**
#     （没在打，撤了当然活）。`A_CB_ACTIVE` 用来区分"没在打"与"概率恰好是 0"。
A_CB_ACTIVE = 0                                   # 1：这支军在某场交战里（1/0）
A_CB_PWIN = A_CB_ACTIVE + 1                       # 1：P(它那一方活、敌全灭)
A_CB_PLOSE = A_CB_PWIN + 1                        # 1：P(它那一方全灭)
A_CB_PDRAW = A_CB_PLOSE + 1                       # 1：P(同归于尽)
A_CB_PHOLD = A_CB_PDRAW + 1                       # 1：P(它那一方是唯一幸存者 ⇒ 占地)
A_CB_R0 = A_CB_PHOLD + 1                          # +CB_ROUND_BINS：轮数累积分布
A_CB_PWIN_REINF = A_CB_R0 + CB_ROUND_BINS         # 1：双方可及增援到齐后的 P(它那一方赢)
A_CB_EROUNDS = A_CB_PWIN_REINF + 1                # 1：期望轮数 ÷ PROB_ROUND_SCALE
A_CB_ELOSS = A_CB_EROUNDS + 1                     # 1：期望掉血 ÷ PROB_LOSS_SCALE
A_RETREAT = A_CB_ELOSS + 1                        # 1：撤退后活下来的概率（没在打 ⇒ 1.0）
A_EXTRA = A_RETREAT + 1
#   = 1(ACTIVE) + 4(赢/输/同归/占地) + CB_ROUND_BINS(轮数档) + 1(增援) + 2(期望)
#     + 1(撤退) = 9 + CB_ROUND_BINS（当前 **14**）

