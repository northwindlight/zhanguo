# ===========================================================================
# 4. 国祚（用户 2026-09-24 四条，逐步问准的）
# ===========================================================================
#   「多国的情况下拿下一两个市政厅游戏并没有结束，应该也纳入评分，**分数非常高**」
#   「**拿下市政厅不代表灭国**，例如每个国家有两个市政厅呢？」
#   「应该是**联盟胜利或者单国胜利**」
#   「**赚厅和丢厅都记分了吗**」   ← 这一条把上一版的不对称戳出来了
#
#   ⇒ 计分单位是**一座厅**（不是"一个被灭的国"），而且**双向**：
#        `+ W_HALL × (我的厅 + 0.5×盟友的厅)`
#
#   ★★ **对手的厅不进分数**（用户 2026-09-24 纠正：「**分数是针对于自己而言，得厅加分，
#      丢厅扣分，和对面几个厅有半毛钱关系？**」）。我上一版写成 `− 对手的厅`，两处错：
#        ① **重复计** —— 引擎实测「打下一座对手的厅 ⇒ 那格 `owner` 变成我、建筑保留」
#           （`甲厅 1→2`）⇒ 拿下已经体现在"我的厅 +1"里，再从对手那侧扣一次就是记两遍。
#        ② **迷雾悖论** —— `halls_of(对手, mask)` 只数看得见的，而势函数取差分
#           ⇒ **侦察到对手的厅反而当场扣分**，"去找厅"成了负收益（那正是本任务要学的）。
#      ⇒ 这一项**不需要任何 mask**（我的/盟友的厅全知），迷雾悖论从根上消失。
#      ★ 对手的厅在 `_one` 的逼近/威胁项里仍然有用 —— 那是**距离差**，侦察到更近的厅
#        是**加分**的（方向正确）。
#
#   ★★ **量纲的锚点**（用户 2026-09-24：「厅改成**等于 10 个步兵**的分数」→ 随后
#      「**改成 20 个步兵**」）：
#        `W_HALL = W_HALL_IN_INFANTRY × W_ARMY`   —— 它是一个**关系**，不是一个孤立的数。
#      ⇒ 调 `W_ARMY`（一个步兵值多少）时**厅会跟着动**；要单独调厅的"倍数"就改
#        `W_HALL_IN_INFANTRY`。
#        我 赚/丢 一座厅 = **±(W_HALL_IN_INFANTRY × W_ARMY)**（当前 ±200）
#        盟友 赚/丢 一座厅 = 再乘 `ALLY_SHARE`（当前 **±100**）
#      ⚠ 这两个是**导入时算的常量**。用 `override(W_ARMY=…)` 扫参时它们**不会跟着变**
#        —— 要一起给（`override(W_ARMY=20, W_HALL=400)`），或改 `W_HALL_IN_INFANTRY`。
#        这是有意的：不做隐式派生（本项目对"魔法"的反感见 `feedback` 记忆）。
W_HALL_IN_INFANTRY = 20.0
W_HALL = W_HALL_IN_INFANTRY * W_ARMY

