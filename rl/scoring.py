ALLY_SHARE = 0.5        # 盟友那一份的折扣
ALLY_DEAD = 0.0         # 盟友已亡时它那一份的贡献。**口径未定，暂取 0（= 跳过）**。
#   `_one` 对亡国返回 −INF，而本沙盒的胜负只看**我的实体** ⇒ 让"盟友亡"等价于"我亡"
