def as_dict() -> dict:
    """当前整张表（记进日志/实验记录用 —— 否则"这个数是哪版先验跑出来的"就说不清）。"""
    g = globals()
    return {k: g[k] for k in _TUNABLE}


@contextlib.contextmanager
def override(**kw):
    """临时改先验：`with scoring.override(W_ARMY=20): …`（退出时**必定**还原）。

    ★ 为什么不让人直接赋值：扫参脚本里忘了改回去，就会把"上一个实验的先验"
      带进下一个实验，**而那种错不报错**。用 with 保证还原。
    """
    bad = set(kw) - set(_TUNABLE)
    if bad:
        raise KeyError(f"不是可调先验：{sorted(bad)}；可调的只有 {list(_TUNABLE)}")
    g = globals()
    old = {k: g[k] for k in kw}
    g.update(kw)
    try:
        yield
    finally:
        g.update(old)


def describe() -> str:
    """一行摘要（建网/开局时打出来，方便对照实验）。

    ★ 表里**不全是数**（`ROUND_BIN_EDGES` 是元组）⇒ 别一律 `{:g}` 格式化，
      那会在**打印日志的时候**炸（而日志恰恰是最需要它不炸的地方）。
    """
    def _fmt(v):
        return f"{v:g}" if isinstance(v, (int, float)) else repr(v)

    return " ".join(f"{k}={_fmt(v)}" for k, v in as_dict().items())