# 5. 势函数差分的压缩尺度（`train._reward` 用）
# ===========================================================================
#   `reward = tanh((score(s') − score(s)) / REWARD_TANH_SCALE)`
#   ⇒ 一步之内 Δ 达到这个尺度就**饱和到 ±1**。
#
#   ★★ **它必须和 `W_HALL` 同量级，否则"厅 = 10 个步兵"这个口径是空的**：
#      `REWARD_TANH_SCALE = 20` 时，`tanh(100/20)=tanh(5)≈0.9999`、`tanh(500/20)≈1.0`
#      ⇒ **厅值 100 还是 500 在奖励上完全一样**（都饱和），连"10 个步兵"和"2 个步兵"
#        也分不开（2×10=20 已经饱和）。那等于用户的改动**静默失效**。
#   ⇒ 定它 **= 一个"大事件"的尺度 = `W_HALL_IN_INFANTRY × W_ARMY`**：
#         · 拿下/丢掉一座厅 ⇒ 恰好饱和到 ±1（"分数非常高"）
#         · 一个步兵 ⇒ `tanh(0.1)≈0.1`；十个步兵 ⇒ 饱和
#      ⇒ 奖励尺度**可读**：0.1 ≈ 一个步兵、1.0 ≈ 一座厅，中间线性可比。
REWARD_TANH_SCALE = W_HALL_IN_INFANTRY * W_ARMY

