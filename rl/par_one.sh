#!/usr/bin/env bash
# 跑**一个** worker；进程一旦真的退出（OOM / 崩溃 / 被 kill）就**自动拉起来**。
#
#   par_one.sh <日志文件> <存档路径> <命令行...>
#
# ★★★ 为什么要有它（2026-09-26 实测）：
#   用户：「这个 oom 是因为我们这个程序有内存泄露，原因没查明，你弄定时重启进程了吗」
#   现场：免费机 8 个 worker 跑 3 小时，**3 个被 OOM 杀掉**（退出码 137），
#   而**死了没人拉** —— tmux 会话还在、日志里一行 `[mem4 退出码 137]`，
#   然后它就那么躺着直到我发现。⇒ 真正咬人的不是泄漏，是**没有恢复**。
#
# ★★ 两层重启**互不冲突**，这一点是关键：
#   · `--restart-after N` 走的是 `os.execv` —— **进程映像被替换，进程并不退出**
#     ⇒ 本脚本的 `while` **看不到**它，不会重复重启（正常轮转照旧）。
#   · 本脚本只管**真的退出**（OOM/崩溃）那一类。
#
# ★★★ 重来时**必须带 `--resume <存档>`**（且只在档存在时带）：
#   不带就从 it0 重头训，而 `--out` 里那份是几百个 iter 的成果 —— **静默重来**，
#   日志上只会看到"又从头开始了"，没有任何报错。⇒ 用 `[ -f ]` 判，第一次没有档就裸跑。
set -uo pipefail

LOG="${1:?用法: par_one.sh <日志> <存档> <命令行...>}"
OUT="${2:?用法: par_one.sh <日志> <存档> <命令行...>}"
shift 2

while true; do
  if [ -f "$OUT" ]; then
    "$@" --resume "$OUT" 2>&1 | tee -a "$LOG"
  else
    "$@" 2>&1 | tee -a "$LOG"
  fi
  ec="${PIPESTATUS[0]}"
  # ★ 退出码**必须**落在日志里（同一类教训：只留在 tmux 窗格里，进程一退窗格就没了）
  echo "[退出码 $ec] ⇒ 10 秒后自动重来（$(date '+%m-%d %H:%M:%S')）" | tee -a "$LOG"
  sleep 10
done
